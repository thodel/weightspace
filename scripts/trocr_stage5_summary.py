#!/usr/bin/env python3
"""Stage 5 discovery summary (docs/TROCR_STAGE5_PREREG.md sections 5 and 6): per model and per setting (seed-mean) Δ against the subject, difference to arm I, class.
    PYTHONPATH=. ~/atr-cache/trocr/venv/bin/python scripts/trocr_stage5_summary.py > docs/trocr/stage5_summary.md
Reads docs/trocr/stage5_reads.jsonl (discovery rows) and the arm-I and baseline rows of docs/trocr/stage4_discovery.jsonl. Reads no model and no held-out line."""
import json
import re
from collections import defaultdict
from pathlib import Path

from wsp import data, metrics, stage5
import scripts.trocr_stage5_read as R

rows = [json.loads(l) for l in Path(R.OUT).read_text().splitlines()]
shams = [r for r in rows if r["what"] == "discovery" and r["name"].startswith("sham")]
disc = [r for r in rows if r["what"] == "discovery" and not r["name"].startswith(("check-", "sham"))]
D = R.jl(R.DISC)
lines = R.lines("discovery")
clusters = [metrics.page_of(r["key"]) for r in lines]
pp = lambda x: f"{100 * x:+.2f}"
ci = lambda c: f"[{100 * c[0]:+.2f}, {100 * c[1]:+.2f}]"


def cmp(subject, ed, label):
    base = [tuple(x) for x in next(r for r in D if r["subject"] == subject and r["what"] == "baseline")["edits"]]
    arm = [tuple(x) for x in next(r for r in D if r["subject"] == subject and r["what"] == "armI")["edits"]]
    ed = [tuple(x) for x in ed]
    own = metrics.bootstrap_delta(base, ed, clusters=clusters, resamples=2000)
    diff = metrics.bootstrap_delta(arm, ed, clusters=clusters, resamples=2000)
    return own, diff, stage5.classify(own["delta_cer"], own["ci95_cluster"], diff["delta_cer"], diff["ci95_cluster"])


out = []
for subj in "AB":
    arm = next(r for r in D if r["subject"] == subj and r["what"] == "armI")
    out.append(f"\n### Subject {subj} (arm I α {arm['alpha']}: discovery Δ {pp(arm['delta_cer'])} {ci(arm['ci95_cluster'])})\n")
    out.append("| model | practice Δ | discovery CER | discovery Δ | vs arm I | class |\n|---|---|---|---|---|---|")
    mine = [r for r in disc if r["subject"] == subj]
    prac = {r["name"]: r for r in rows if r["what"] == "practice" and r["subject"] == subj}
    groups = defaultdict(list)
    for r in sorted(mine, key=lambda r: r["name"]):
        own, diff, cls = cmp(subj, r["edits"], r["name"])
        p = prac.get(r["name"])
        out.append(f"| {r['name']} | {pp(p['delta_cer']) if p else '–'} | {100 * r['cer']:.2f} | {pp(own['delta_cer'])} {ci(own['ci95_cluster'])} | {pp(diff['delta_cer'])} {ci(diff['ci95_cluster'])} | {cls} |")
        m = re.match(r"(c4(?:small|big)-[AB]-lr[0-9e.-]+)-s\d$", r["name"])
        if m:
            groups[m.group(1)].append(r)
    for g, rs in groups.items():
        if len(rs) < 2:
            continue
        mean = stage5.seed_mean_edits([r["edits"] for r in rs])
        own, diff, cls = cmp(subj, mean, g)
        out.append(f"| **{g} (mean of {len(rs)} seeds)** | | {100 * sum(e for e, _ in mean) / sum(c for _, c in mean):.2f} | {pp(own['delta_cer'])} {ci(own['ci95_cluster'])} | {pp(diff['delta_cer'])} {ci(diff['ci95_cluster'])} | **{cls}** |")
        ds = [100 * r["delta_cer"] for r in rs]
        out.append(f"| seed spread of {g} | | | min {min(ds):+.2f}, max {max(ds):+.2f}, sd {(sum((d - sum(ds) / len(ds)) ** 2 for d in ds) / (len(ds) - 1)) ** .5:.2f} | | |")
    for fin in sorted({r["name"].split(":")[1] for r in shams if r["subject"] == subj}):
        ds = [r for r in shams if r["subject"] == subj and r["name"].endswith(":" + fin)]
        out.append(f"\nShams of {fin} (5, discovery): Δ from {pp(min(r['delta_cer'] for r in ds))} to {pp(max(r['delta_cer'] for r in ds))}, all intervals contain 0: "
                   f"{all(r['ci95_cluster'][0] < 0 < r['ci95_cluster'][1] for r in ds)}; largest gain {pp(min(r['delta_cer'] for r in ds))}")
    sel = stage5.select_other([{"name": r["name"], "delta_cer": r["delta_cer"], "ci95_cluster": r["ci95_cluster"]} for r in mine])
    out.append(f"\nSelection rule of section 7 (`select_other`) for subject {subj}: **{sel['name'] if sel else 'none eligible'}**"
               + (f" (discovery Δ {pp(sel['delta_cer'])} {ci(sel['ci95_cluster'])})" if sel else "") + "\n")
print("# Stage 5, discovery-half summary (generated by scripts/trocr_stage5_summary.py)\n\nΔ = CER(model) − CER(unedited subject), points, page-clustered 95 %; vs arm I = CER(model) − CER(arm I), paired. Practice Δ is on the practice set (C4 trained on it: no information).\n" + "\n".join(out))
